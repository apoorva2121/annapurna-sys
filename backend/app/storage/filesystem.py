"""Files on a disk. Local development, every test, and staging until a bucket exists.

**Not a stub.** It is the driver the owner chose for staging on 2026-09-18, which means it is
production code on a real deployment, and it is the driver the behaviour tests run against first.

**Its limitation is real and stated rather than hidden.** On Cloud Run the writable filesystem is
`/tmp`, which is memory and which goes away when the instance recycles. An upload made on Monday
may not be there on Tuesday. That is a property of the deployment the owner chose knowingly; it is
written at the top of the manual script so a missing photograph reads as expected rather than as a
defect, and switching staging to a bucket is three environment variables.

**A key is a path, so a key must not be able to escape.** Keys are generated by the service and
never derived from a filename, but this driver is the last place that can be sure: the resolved
path is checked to be inside the root, and anything else raises before a byte is written. Belt and
braces, because the cost of being wrong here is arbitrary file write.
"""

from __future__ import annotations

import asyncio
import shutil
import tempfile
from pathlib import Path

from app.storage.port import ObjectFacts, UploadInstruction


class FilesystemStorage:
    """Objects under one root directory, one file per key."""

    driver = "filesystem"
    presigns_uploads = False

    def __init__(self, root: str | None = None) -> None:
        # An empty root is not a misconfiguration; it is "put them somewhere sensible". On Cloud
        # Run that resolves to /tmp, which is exactly where a container may write.
        self._root = (
            Path(root).expanduser().resolve()
            if root
            else Path(tempfile.gettempdir()) / "restaurant-os-attachments"
        )

    @property
    def root(self) -> Path:
        return self._root

    def _path(self, key: str) -> Path:
        candidate = (self._root / key).resolve()
        # `is_relative_to` rather than string prefixing: '/data/attachments-evil' starts with
        # '/data/attachments' and is not inside it.
        if not candidate.is_relative_to(self._root):
            raise ValueError("storage key escapes the storage root")
        return candidate

    async def presigned_put(
        self, key: str, *, content_type: str, size_bytes: int
    ) -> UploadInstruction:
        raise NotImplementedError("the filesystem driver does not presign uploads")

    async def write(self, key: str, data: bytes, *, content_type: str) -> None:
        # `content_type` is part of the port because S3 stores it on the object. A filesystem has
        # nowhere to put it, and the database already holds the declared type — so it is accepted
        # and ignored rather than the port growing a second, driver-shaped write method.
        del content_type
        path = self._path(key)

        def _write() -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            # Written beside the target and moved into place, so a half-written file is never
            # visible under its key — `facts()` would otherwise report a truncated size to the
            # confirmation check and turn a network failure into a validation failure.
            with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as handle:
                handle.write(data)
                staged = Path(handle.name)
            shutil.move(str(staged), str(path))

        await asyncio.to_thread(_write)

    async def download_url(self, key: str, *, file_name: str) -> str | None:
        """Nothing to sign. The download route serves the bytes itself, with the headers that
        replace the separate-origin defence."""
        del key, file_name
        return None

    async def read(self, key: str, count: int | None = None) -> bytes:
        path = self._path(key)

        def _read() -> bytes:
            with path.open("rb") as handle:
                return handle.read() if count is None else handle.read(count)

        return await asyncio.to_thread(_read)

    async def facts(self, key: str) -> ObjectFacts | None:
        path = self._path(key)

        def _facts() -> ObjectFacts | None:
            if not path.is_file():
                return None
            return ObjectFacts(size_bytes=path.stat().st_size)

        return await asyncio.to_thread(_facts)

    async def delete(self, key: str) -> None:
        path = self._path(key)

        def _delete() -> None:
            path.unlink(missing_ok=True)

        await asyncio.to_thread(_delete)
